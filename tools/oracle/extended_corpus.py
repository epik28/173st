#!/usr/bin/env python3
"""Deterministic RNG-002 inputs and coverage audit; no Rust-derived answers."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / 'tests/fixtures/rng/extended.tsv'
SEEDS = [0, 1, -1, 42, -(2**63), 2**63-1, 123456789, -987654321, 281474976710655, 998877665544]
BOUNDS = [1, 2, 3, 7, 16, 17, 1073741824, 1073741825, 2147483647, 0, -1, -(2**31)]


def corpus():
    lines = ['# RNG-002 inputs generated by tools/oracle/extended_corpus.py; no expected outputs']
    for index, seed in enumerate(SEEDS):
        ops = []
        for cycle in range(100):
            ops.extend(['int', 'long', 'boolean', 'float', 'double',
                        f'bound:{BOUNDS[cycle % len(BOUNDS)]}', f'bound:{BOUNDS[(cycle+5) % len(BOUNDS)]}',
                        'int', 'long', 'double', 'float'])
            if cycle % 19 == 0:
                ops.append(f'seed:{SEEDS[(cycle+index) % len(SEEDS)]}')
        lines.append(f'mixed-{index}\t{seed}\t' + ';'.join(ops))
    lines.append('rejection\t0\t' + ';'.join(['bound:1073741825'] * 2048))
    tail = 'int;long;boolean;float;double;bound:17;int'
    lines.extend(['invalid-control\t42\t' + tail,
                  'invalid-chain\t42\tbound:0;bound:-1;bound:-2147483648;' + tail])
    for index, seed in enumerate(SEEDS[:6]):
        lines.extend([f'reseed-control-{index}\t{seed}\t{tail}',
                      f'reseed-chain-{index}\t77\tlong;double;seed:{seed};{tail}'])
    return ('\n'.join(lines) + '\n').encode()


def verify():
    data = corpus()
    assert FIXTURE.read_bytes() == data, 'fixture differs from deterministic generator'
    counts = Counter()
    total = 0
    for line in data.decode().splitlines():
        if line.startswith('#'): continue
        tokens = line.split('\t')[2].split(';')
        counts.update(token.split(':')[0] for token in tokens)
        total += len(tokens)
    assert 10000 <= total <= 100000
    build = ROOT / 'artifacts/oracle-extended-check'
    build.mkdir(parents=True, exist_ok=True)
    subprocess.run(['javac', '-d', str(build), str(ROOT/'tools/oracle/src/RandomExtendedOracle.java'),
                    str(ROOT/'tools/oracle/src/RejectionMutation.java')], check=True, timeout=30)
    command = ['java', '-cp', str(build), 'RandomExtendedOracle']
    def execute(value):
        return subprocess.run(command, input=value, capture_output=True, timeout=20)
    first, second = execute(data), execute(data)
    assert first.returncode == second.returncode == 0 and not first.stderr and not second.stderr
    assert first.stdout == second.stdout and len(first.stdout.splitlines()) == total
    (build/'reference.stdout.tsv').write_bytes(first.stdout)
    grouped = {}
    for line in first.stdout.decode().splitlines():
        case, _, op, value = line.split('\t')
        grouped.setdefault(case, []).append((op, value))
    assert grouped['invalid-control'] == grouped['invalid-chain'][3:]
    for index in range(6):
        assert grouped[f'reseed-control-{index}'] == grouped[f'reseed-chain-{index}'][3:]
    invalid = [b' \n', b'\t\n', b'x\t0\tunknown\n', b'x\t0\t\n', b'x\t0\tint;\n',
               b'x\t0\t;int\n', b'x\t0\tint;;int\n', b'x\t0\tint \n',
               b'x\t9223372036854775808\tint\n', b'x\t0\tseed:-9223372036854775809\n',
               b'x\t0\tbound:2147483648\n', b'x\t0\tbound:abc\n', b'x\t0\tseed:1:2\n',
               b'x\t0\tint\nx\t1\tint\n', b'bad id\t0\tint\n',
               b'x\t0\t' + b';'.join([b'int'] * 100001) + b'\n',
               b'x\t0\t' + b';'.join([b'int'] * 50001) + b'\ny\t0\t' + b';'.join([b'int'] * 50000) + b'\n']
    for value in invalid:
        result = execute(value)
        assert result.returncode != 0 and result.stderr, value[:80]
    maximum = execute(b'x\t0\t' + b';'.join([b'int'] * 100000) + b'\n')
    assert maximum.returncode == 0 and len(maximum.stdout.splitlines()) == 100000
    mutation = subprocess.run(['java','-cp',str(build),'RejectionMutation'],capture_output=True,check=True,timeout=10)
    (build/'synthetic-no-rejection.tsv').write_bytes(mutation.stdout)
    rows = [tuple(map(int, line.split(b'\t'))) for line in mutation.stdout.splitlines()]
    assert [value for _, value, _ in rows] == [int(value) for _, value in grouped['rejection']]
    mismatches = [row for row in rows if row[1] != row[2]]
    assert mismatches
    report = {'kind':'Java adapter audit; synthetic no-rejection mutation is not Rust parity',
              'value_count':total,'operations':dict(counts),'case_count':len(grouped),
              'input_sha256':hashlib.sha256(data).hexdigest(),'invalid_inputs_rejected':len(invalid),
              'maximum_accepted':100000,'rejection_calls':2048,
              'synthetic_rejection_mismatches':len(mismatches),'first_rejection_mismatch':mismatches[0],
              'state_checks':'invalid bound consumes no state; reseed matches new Random (6 seeds)'}
    (build/'audit.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    if args.write:
        FIXTURE.parent.mkdir(parents=True,exist_ok=True)
        FIXTURE.write_bytes(corpus())
    verify()

if __name__ == '__main__': main()
