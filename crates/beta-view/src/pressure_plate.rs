pub(crate) fn append(
    mesh: &mut Mesh,
    pos: [i32; 3],
    block: BlockData,
    below: BlockData,
    bottom_visible: bool,
    minimum_light: u8,
    limits: MeshLimits,
) -> Result<(), ViewError> {
    let count = if bottom_visible { 36 } else { 30 };
    if mesh.vertices.len().saturating_add(count) > limits.max_vertices.min(crate::MAX_MESH_VERTICES)
        || mesh.indices.len().saturating_add(count)
            > limits.max_indices.min(crate::MAX_MESH_INDICES)
    {
        return Err(ViewError::MeshLimitExceeded {
            vertices: mesh.vertices.len() + count,
            indices: mesh.indices.len() + count,
        });
    }
    let model = usize::from(block.id == 72) * 2 + usize::from(block.metadata == 1);
    for (i, bits) in MODELS[model].iter().enumerate() {
        let face = i / 6;
        if face == 0 && !bottom_visible {
            continue;
        }
        let light = if face == 0 { below } else { block };
        mesh.vertices.push(Vertex {
            position: [
                f32::from_bits(bits[0]) + pos[0] as f32,
                f32::from_bits(bits[1]) + pos[1] as f32,
                f32::from_bits(bits[2]) + pos[2] as f32,
            ],
            uv: [f32::from_bits(bits[3]), f32::from_bits(bits[4])],
            block_light: light.block_light,
            sky_light: light.sky_light,
            minimum_light,
            shade: crate::face_shade(face as u8)?,
            tint: [1.0; 3],
            tint_after_light: false,
        });
        mesh.indices.push(mesh.vertices.len() as u32 - 1);
    }
    mesh.visible_faces += count / 6;
    Ok(())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn plates_all_states_match_native_vertices() {
        let mut count = 0;
        for line in include_str!("../../../tests/fixtures/pressure_plate_render/native.tsv")
            .lines()
            .filter(|l| l.starts_with("vertex\t"))
        {
            let f: Vec<_> = line.split('\t').collect();
            let id = f[1].parse().unwrap();
            let metadata = f[2].parse().unwrap();
            let index: usize = f[3].parse().unwrap();
            let bits: Vec<u32> = f[4..9]
                .iter()
                .map(|s| u32::from_str_radix(s, 16).unwrap())
                .collect();
            let block = BlockData {
                id,
                metadata,
                block_light: 0,
                sky_light: 15,
            };
            let mut mesh = Mesh::default();
            append(
                &mut mesh,
                [0, 0, 0],
                block,
                block,
                true,
                0,
                MeshLimits::default(),
            )
            .unwrap();
            assert_eq!(
                mesh.vertices[index].position.map(f32::to_bits),
                [bits[0], bits[1], bits[2]],
                "id={id} meta={metadata} vertex={index}"
            );
            assert_eq!(
                mesh.vertices[index].uv.map(f32::to_bits),
                [bits[3], bits[4]],
                "id={id} meta={metadata} vertex={index}"
            );
            count += 1;
        }
        assert_eq!(count, 2 * 16 * 36);
    }
}
