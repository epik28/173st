pub(crate) fn append(
    mesh: &mut Mesh,
    pos: [i32; 3],
    block: BlockData,
    minimum_light: u8,
    limits: MeshLimits,
) -> Result<(), ViewError> {
    if mesh.vertices.len().saturating_add(12) > limits.max_vertices.min(crate::MAX_MESH_VERTICES)
        || mesh.indices.len().saturating_add(12) > limits.max_indices.min(crate::MAX_MESH_INDICES)
    {
        return Err(ViewError::MeshLimitExceeded {
            vertices: mesh.vertices.len() + 12,
            indices: mesh.indices.len() + 12,
        });
    }
    let base = mesh.vertices.len() as u32;
    let kind = match block.id {
        27 => 0,
        28 => 1,
        _ => 2,
    };
    let model = MODEL_INDEX[kind][usize::from(block.metadata & 15)];
    for (i, bits) in MODELS[model].iter().enumerate() {
        mesh.vertices.push(Vertex {
            position: [
                f32::from_bits(bits[0]) + pos[0] as f32,
                f32::from_bits(bits[1]) + pos[1] as f32,
                f32::from_bits(bits[2]) + pos[2] as f32,
            ],
            uv: [f32::from_bits(bits[3]), f32::from_bits(bits[4])],
            block_light: block.block_light,
            sky_light: block.sky_light,
            minimum_light,
            shade: 1.0,
            tint: [1.0; 3],
            tint_after_light: false,
        });
        mesh.indices.push(base + i as u32);
    }
    mesh.visible_faces += 2;
    Ok(())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn rails_all_states_match_native_vertices() {
        let mut count = 0;
        for line in include_str!("../../../tests/fixtures/rail_render/native.tsv")
            .lines()
            .filter(|line| line.starts_with("vertex\t"))
        {
            let row: Vec<_> = line.split('\t').collect();
            let id = row[1].parse().unwrap();
            let meta = row[2].parse().unwrap();
            let index: usize = row[3].parse().unwrap();
            let bits: Vec<u32> = row[4..9]
                .iter()
                .map(|s| u32::from_str_radix(s, 16).unwrap())
                .collect();
            let mut mesh = Mesh::default();
            append(
                &mut mesh,
                [0, 0, 0],
                BlockData {
                    id,
                    metadata: meta,
                    block_light: 0,
                    sky_light: 15,
                },
                0,
                MeshLimits::default(),
            )
            .unwrap();
            let v = mesh.vertices[index];
            assert_eq!(
                v.position.map(f32::to_bits),
                [bits[0], bits[1], bits[2]],
                "id={id} meta={meta} vertex={index}"
            );
            assert_eq!(
                v.uv.map(f32::to_bits),
                [bits[3], bits[4]],
                "id={id} meta={meta} vertex={index}"
            );
            count += 1;
        }
        assert_eq!(count, 3 * 16 * 12);
    }
}
